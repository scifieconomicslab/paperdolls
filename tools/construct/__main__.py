"""Construct a region's scene.json from a description.

    python -m construct generate --spec spec.json --out scene.json
    python -m construct generate --out scene.json                 # default town
    python -m construct validate scene.json
    python -m construct spec                                   # print a sample spec

Spec keys (all optional, defaults in parentheses):
    name ("Constructed town"), extent_m ([640, 480]), seed (42),
    street_pitch_m (44), avenue_every (4),
    park_blocks (2), pond (true), square (true),
    centre_frac (0.18)       # share of the middle that is "centre" district
    industrial_frac (0.15)   # share of the outer edges that is "industrial"
    family ("real")          # real | historical | fantasy | scifi
    palette ("nw")           # palette family id from reference/render/palettes.json
    structures ([])          # explicit non-building structures: {kind, footprint, levels?, height?}
"""
import argparse
import json
import sys
from pathlib import Path

from .generate import generate

DEFAULT_SPEC = {
    "name": "Ashford (constructed)",
    "extent_m": [640, 480],
    "seed": 42,
    "street_pitch_m": 44,
    "avenue_every": 4,
    "park_blocks": 2,
    "pond": True,
    "square": True,
    "family": "real",
    "palette": "nw",
    "structures": [],
}


def cmd_generate(a):
    spec = None
    if a.spec:
        spec = json.loads(Path(a.spec).read_text())
    scene = generate(spec)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(scene, separators=(",", ":"), allow_nan=False))
    c = {k: len(v) for k, v in (("buildings", scene["buildings"]), ("structures", scene["structures"]), ("roads", scene["roads"]), ("landuse", scene["landuse"]), ("trees", scene["trees"]))}
    from collections import Counter
    classes = Counter(b["economic_class"] for b in scene["buildings"])
    report = [
        f"# Constructed region: {scene['area']['name']}",
        "",
        f"All data is synthetic — generated by `python -m construct` with seed {spec.get('seed', 42) if spec else 42}. Nothing here describes or locates a real place.",
        "",
        "## Counts",
        "",
        f"- buildings: {c['buildings']}",
        f"- structures: {c['structures']}",
        f"- roads: {c['roads']}",
        f"- landuse polygons: {c['landuse']}",
        f"- trees: {c['trees']}",
        f"- extent: {scene['area']['extent_m'][0]} x {scene['area']['extent_m'][1]} m",
        "",
        "## Economic classes (generated)",
        "",
        *[f"- {k}: {v}" for k, v in sorted(classes.items(), key=lambda kv: -kv[1])],
        "",
        "## Provenance",
        "",
        "Every building's `economic_class_source` is `generated`. Assignments come from the district mixture by cell position",
        "(residential / centre / industrial at the edges), with storeys drawn from the district's bands. No tags were read.",
        "",
    ]
    md = out.with_name(out.stem + "_report.md")
    md.write_text("\n".join(report))
    print(f"wrote {out}: {c['buildings']} buildings, {c['structures']} structures, {c['roads']} roads, {c['landuse']} landuse, {c['trees']} trees")
    print(f"report: {md}")
    return 0


def cmd_validate(a):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
    from ingest.validate import validate_scene
    scene = json.loads(Path(a.input).read_text())
    errors, warnings = validate_scene(scene)
    for w in warnings:
        print("WARNING:", w)
    if errors:
        for e in errors:
            print("ERROR:", e)
        return 1
    print("valid")
    return 0


def cmd_spec(_a):
    print(json.dumps(DEFAULT_SPEC, indent=2))
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python -m construct")
    sub = ap.add_subparsers(required=True)
    s = sub.add_parser("generate", help="generate a region's scene.json")
    s.add_argument("--spec", help="spec JSON (see `construct spec`); defaults shown if omitted")
    s.add_argument("--out", default="scene.json")
    s.set_defaults(f=cmd_generate)
    s = sub.add_parser("validate", help="validate a generated scene.json")
    s.add_argument("input")
    s.set_defaults(f=cmd_validate)
    s = sub.add_parser("spec", help="print a sample spec")
    s.set_defaults(f=cmd_spec)
    args = ap.parse_args(argv)
    return args.f(args)


if __name__ == "__main__":
    sys.exit(main())
